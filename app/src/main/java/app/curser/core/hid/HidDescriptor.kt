object Hid {
    const val REPORT_MOUSE = 1
    const val REPORT_KEYBOARD = 2
    const val REPORT_CONSUMER = 3

    const val CONSUMER_GLOBE = 0x029D
    const val CONSUMER_LAUNCHPAD = 0x02A0

    const val MOD_LCTRL = 0x01
    const val MOD_LSHIFT = 0x02
    const val MOD_LALT = 0x04
    const val MOD_LGUI = 0x08

    const val KEY_A = 0x04
    const val KEY_C = 0x06
    const val KEY_D = 0x07
    const val KEY_H = 0x0B
    const val KEY_N = 0x11
    const val KEY_S = 0x16
    const val KEY_TAB = 0x2B
    const val KEY_SPACE = 0x2C
    const val KEY_MINUS = 0x2D
    const val KEY_EQUAL = 0x2E
    const val KEY_F11 = 0x44
    const val KEY_RIGHT = 0x4F
    const val KEY_LEFT = 0x50
    const val KEY_DOWN = 0x51
    const val KEY_UP = 0x52

    const val MOUSE_PAYLOAD_SIZE = 7
    const val KEYBOARD_PAYLOAD_SIZE = 8
    const val CONSUMER_PAYLOAD_SIZE = 2

    private val DESCRIPTOR_INTS = intArrayOf(
        // Report ID 1: mouse
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01,
        0x85, 0x01,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x05, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x16, 0x01, 0x80, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x06,
        0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06,
        0xC0,
        0xC0,
        // Report ID 2: keyboard
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01,
        0x85, 0x02,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
