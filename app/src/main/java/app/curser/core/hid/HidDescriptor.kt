        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,
        0xC0,
        // Report ID 3: consumer control
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01,
        0x85, 0x03,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03, 0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0
    )

    val DESCRIPTOR: ByteArray = ByteArray(DESCRIPTOR_INTS.size) { DESCRIPTOR_INTS[it].toByte() }

    /** Payload without the report ID byte: buttons, Xlo, Xhi, Ylo, Yhi, wheel, pan. */
    fun mouseReport(buttons: Int, x: Int, y: Int, wheel: Int, pan: Int): ByteArray {
        val cx = x.coerceIn(-32767, 32767)
        val cy = y.coerceIn(-32767, 32767)
        return byteArrayOf(
            (buttons and 0x07).toByte(),
            (cx and 0xFF).toByte(), ((cx shr 8) and 0xFF).toByte(),
            (cy and 0xFF).toByte(), ((cy shr 8) and 0xFF).toByte(),
            wheel.coerceIn(-127, 127).toByte(),
            pan.coerceIn(-127, 127).toByte()
        )
    }

    /** Payload without the report ID byte: modifiers, reserved, key1..key6. key 0 = no key. */
    fun keyboardReport(mods: Int, key: Int): ByteArray =
        byteArrayOf((mods and 0xFF).toByte(), 0, (key and 0xFF).toByte(), 0, 0, 0, 0, 0)

    /** Payload without the report ID byte: one 16-bit usage, little-endian. 0 = released. */
    fun consumerReport(usage: Int): ByteArray =
        byteArrayOf((usage and 0xFF).toByte(), ((usage shr 8) and 0xFF).toByte())
}
